/* =========================================================
   NORMALIZAR TEXTO

   Isso permite que um texto quebrado em várias linhas no HTML:

   Explore Roraima,
   descubra novos lugares...

   seja entendido como uma frase normal.
========================================================= */

function normalizarTexto(texto) {

    return String(texto || "")
        .replace(/\s+/g, " ")
        .trim();

}


/* =========================================================
   IDIOMA ATUAL
========================================================= */

function obterIdiomaSistema() {

    const idioma =
        localStorage.getItem("bventureIdioma");

    if (
        BVENTURE_IDIOMAS_VALIDOS.includes(idioma)
    ) {
        return idioma;
    }

    return BVENTURE_IDIOMA_PADRAO;

}


/* =========================================================
   TRADUZIR TEXTO
========================================================= */

function traduzirTexto(texto, idioma = obterIdiomaSistema()) {

    const original =
        normalizarTexto(texto);

    if (!original) {
        return original;
    }

    if (idioma === "pt") {
        return original;
    }

    return (
        BVENTURE_TRADUCOES[idioma]?.[original]
        ||
        original
    );

}


/* =========================================================
   ATALHO PARA TEXTOS GERADOS PELO JAVASCRIPT

   Exemplo:

   t("Missões")
========================================================= */

function t(texto) {

    return traduzirTexto(texto);

}


/* =========================================================
   TRADUZIR TEXT NODE

   Esta parte é importante porque não substitui o elemento
   inteiro. Assim, SVG, <strong>, <span>, ícones e outros
   elementos internos não são destruídos.
========================================================= */

function traduzirNoTexto(no, idioma) {

    if (!no || no.nodeType !== Node.TEXT_NODE) {
        return;
    }

    const textoVisivel =
        normalizarTexto(no.nodeValue);

    if (!textoVisivel) {
        return;
    }


    /* Guarda o português original apenas uma vez */

    if (!no.__bventureTextoOriginal) {

        no.__bventureTextoOriginal =
            textoVisivel;

    }


    const original =
        no.__bventureTextoOriginal;


    const traducao =
        traduzirTexto(
            original,
            idioma
        );


    /*
        Preserva um espaço antes/depois quando ele já
        existia no texto original.
    */

    const comEspacoAntes =
        /^\s/.test(no.nodeValue);

    const comEspacoDepois =
        /\s$/.test(no.nodeValue);


    no.nodeValue =
        `${comEspacoAntes ? " " : ""}${traducao}${comEspacoDepois ? " " : ""}`;

}


/* =========================================================
   TRADUZIR ATRIBUTOS
========================================================= */

function traduzirAtributos(elemento, idioma) {

    if (!(elemento instanceof Element)) {
        return;
    }


    /* PLACEHOLDER */

    if (
        elemento.hasAttribute("placeholder")
    ) {

        if (
            !elemento.dataset.bventurePlaceholderOriginal
        ) {

            elemento.dataset.bventurePlaceholderOriginal =
                elemento.getAttribute("placeholder");

        }


        elemento.setAttribute(
            "placeholder",
            traduzirTexto(
                elemento.dataset.bventurePlaceholderOriginal,
                idioma
            )
        );

    }


    /* TITLE */

    if (
        elemento.hasAttribute("title")
    ) {

        if (
            !elemento.dataset.bventureTitleOriginal
        ) {

            elemento.dataset.bventureTitleOriginal =
                elemento.getAttribute("title");

        }


        elemento.setAttribute(
            "title",
            traduzirTexto(
                elemento.dataset.bventureTitleOriginal,
                idioma
            )
        );

    }


    /* ARIA-LABEL */

    if (
        elemento.hasAttribute("aria-label")
    ) {

        if (
            !elemento.dataset.bventureAriaOriginal
        ) {

            elemento.dataset.bventureAriaOriginal =
                elemento.getAttribute("aria-label");

        }


        elemento.setAttribute(
            "aria-label",
            traduzirTexto(
                elemento.dataset.bventureAriaOriginal,
                idioma
            )
        );

    }

}


/* =========================================================
   TRADUZIR UMA ÁREA DA PÁGINA
========================================================= */

function traduzirElemento(raiz, idioma) {

    if (!raiz) {
        return;
    }


    /* Traduz atributos da própria raiz */

    if (raiz.nodeType === Node.ELEMENT_NODE) {

        traduzirAtributos(
            raiz,
            idioma
        );

    }


    /*
        TreeWalker percorre apenas os textos.
        Não altera a estrutura HTML.
    */

    const walker =
        document.createTreeWalker(
            raiz,
            NodeFilter.SHOW_TEXT
        );


    const nosTexto = [];

    let noAtual;


    while (
        (
            noAtual =
                walker.nextNode()
        )
    ) {

        const pai =
            noAtual.parentElement;


        if (!pai) {
            continue;
        }


        /*
            Não mexer no conteúdo de scripts,
            estilos etc.
        */

        if (
            pai.closest(
                "script, style, noscript"
            )
        ) {
            continue;
        }


        nosTexto.push(noAtual);

    }


    nosTexto.forEach(
        no => {

            traduzirNoTexto(
                no,
                idioma
            );

        }
    );


    /* Traduz atributos dos elementos */

    if (
        raiz.querySelectorAll
    ) {

        raiz
            .querySelectorAll(
                "[placeholder], [title], [aria-label]"
            )
            .forEach(
                elemento => {

                    traduzirAtributos(
                        elemento,
                        idioma
                    );

                }
            );

    }

}


