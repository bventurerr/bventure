function aplicarIdioma() {

    if (bventureAplicandoIdioma) {
        return;
    }

    


    bventureAplicandoIdioma = true;


    const idioma =
        obterIdiomaSistema();


    document.documentElement.lang =
        idioma === "pt"
            ? "pt-BR"
            : idioma;


    traduzirElemento(
        document.body,
        idioma
    );

    traduzirBlocosHTML(
        idioma
    );


    bventureAplicandoIdioma = false;

}


/* =========================================================
   ALTERAR IDIOMA
========================================================= */

function alterarIdioma(novoIdioma) {

    if (
        !BVENTURE_IDIOMAS_VALIDOS.includes(
            novoIdioma
        )
    ) {

        return false;

    }


    localStorage.setItem(
        "bventureIdioma",
        novoIdioma
    );


    aplicarIdioma();


    window.dispatchEvent(
        new CustomEvent(
            "bventure:idiomaAlterado",
            {
                detail: {
                    idioma:
                        novoIdioma
                }
            }
        )
    );


    return true;

}


/* =========================================================
   OBSERVAR CONTEÚDO CRIADO PELO JAVASCRIPT

   Exemplo:
   - pop-ups
   - cards criados depois
   - mensagens
   - informações dos locais

   Quando algo novo aparece no DOM, tentamos traduzir.
========================================================= */

let bventureObservadorIdioma = null;


function iniciarObservadorIdioma() {

    if (
        bventureObservadorIdioma ||
        !document.body
    ) {
        return;
    }


    bventureObservadorIdioma =
        new MutationObserver(
            mutacoes => {

                if (bventureAplicandoIdioma) {
                    return;
                }


                const idioma =
                    obterIdiomaSistema();


                if (idioma === "pt") {
                    return;
                }


                mutacoes.forEach(
                    mutacao => {

                        mutacao.addedNodes.forEach(
                            no => {

                                if (
                                    no.nodeType ===
                                    Node.TEXT_NODE
                                ) {

                                    traduzirNoTexto(
                                        no,
                                        idioma
                                    );

                                    return;

                                }


                                if (
                                    no.nodeType ===
                                    Node.ELEMENT_NODE
                                ) {

                                    traduzirElemento(
                                        no,
                                        idioma
                                    );

                                }

                            }
                        );

                    }
                );

            }
        );


    bventureObservadorIdioma.observe(
        document.body,
        {
            childList: true,
            subtree: true
        }
    );

}


/* =========================================================
   INICIALIZAÇÃO
========================================================= */

function iniciarSistemaIdiomas() {

    aplicarIdioma();

    iniciarObservadorIdioma();

}


if (
    document.readyState === "loading"
) {

    document.addEventListener(
        "DOMContentLoaded",
        iniciarSistemaIdiomas
    );

}
else {

    iniciarSistemaIdiomas();

}


